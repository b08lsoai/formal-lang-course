from collections import defaultdict, deque

import networkx as nx
from pyformlang.cfg import CFG, Production, Terminal, Variable


def cfg_to_weak_normal_form(cfg: CFG) -> CFG:
    """Weak Chomsky normal form: ``A -> B C``, ``A -> a`` and ``A -> epsilon``."""
    cfg = _lift_terminals(cfg)
    cfg = _binarize(cfg)
    cfg = cfg.eliminate_unit_productions()
    cfg = cfg.remove_useless_symbols()
    # pyformlang's unit elimination re-adds every production once per variable
    # (its unit pairs include the reflexive ones), so drop the copies.
    return CFG(start_symbol=cfg.start_symbol, productions=set(cfg.productions))


def _fresh_variable(prefix: str, used: set[Variable]) -> Variable:
    """First ``<prefix>_<n>`` that does not clash with the existing variables."""
    index = 0
    while True:
        variable = Variable(f"{prefix}_{index}")
        index += 1
        if variable not in used:
            used.add(variable)
            return variable


def _lift_terminals(cfg: CFG) -> CFG:
    """Lift terminals out of bodies longer than one symbol into fresh variables."""
    used = set(cfg.variables)
    preterminals: dict[Terminal, Variable] = {}
    productions: set[Production] = set()

    for production in cfg.productions:
        body = list(production.body)
        if len(body) > 1:
            for position, symbol in enumerate(body):
                if isinstance(symbol, Terminal):
                    if symbol not in preterminals:
                        preterminals[symbol] = _fresh_variable("T", used)
                        productions.add(Production(preterminals[symbol], [symbol]))
                    body[position] = preterminals[symbol]
        productions.add(Production(production.head, body))

    return CFG(start_symbol=cfg.start_symbol, productions=productions)


def _binarize(cfg: CFG) -> CFG:
    """Split every body longer than two symbols into a chain of binary rules."""
    used = set(cfg.variables)
    productions: set[Production] = set()

    for production in cfg.productions:
        body = list(production.body)
        while len(body) > 2:
            right = body.pop()
            left = body.pop()
            intermediate = _fresh_variable("B", used)
            productions.add(Production(intermediate, [left, right]))
            body.append(intermediate)
        productions.add(Production(production.head, body))

    return CFG(start_symbol=cfg.start_symbol, productions=productions)


class WCNFGrammar:
    """A CFG converted to weak Chomsky normal form and indexed by rule body.

    ``epsilon_productions`` contains heads of ``A -> epsilon`` rules.
    ``terminal_productions[a]`` contains heads of ``A -> a`` rules.
    ``binary_productions[B, C]`` contains heads of ``A -> B C`` rules.
    """

    def __init__(self, cfg: CFG) -> None:
        cfg = cfg_to_weak_normal_form(cfg)
        self.start_symbol = cfg.start_symbol
        self.variables = cfg.variables
        self.epsilon_productions: set[Variable] = set()
        self.terminal_productions: dict[str, set[Variable]] = {}
        self.binary_productions: dict[tuple[Variable, Variable], set[Variable]] = {}

        for production in cfg.productions:
            head, body = production.head, production.body
            if len(body) == 0:
                self.epsilon_productions.add(head)
            elif len(body) == 1:
                self.terminal_productions.setdefault(body[0].value, set()).add(head)
            else:
                self.binary_productions.setdefault((body[0], body[1]), set()).add(head)

    def __len__(self) -> int:
        """Number of productions, counting each head in a group separately."""
        return (
            len(self.epsilon_productions)
            + sum(map(len, self.terminal_productions.values()))
            + sum(map(len, self.binary_productions.values()))
        )


def hellings_based_cfpq(
    cfg: CFG,
    graph: nx.DiGraph,
    start_nodes: set[int] | None = None,
    final_nodes: set[int] | None = None,
) -> set[tuple[int, int]]:
    """Finds all pairs of nodes (u, v) such that there is a path from u to v
    whose edge labels form a word in the language generated by ``cfg``.

    An empty ``start_nodes`` / ``final_nodes`` means every vertex.
    """
    grammar = WCNFGrammar(cfg)

    starts = set(graph.nodes) if not start_nodes else set(start_nodes)
    finals = set(graph.nodes) if not final_nodes else set(final_nodes)

    # reached[(i, j)] is the set of variables deriving some path i -> j.
    reached: dict[tuple[int, int], set[Variable]] = defaultdict(set)
    # outgoing[i][j] and incoming[j][i] mirror reached, indexed by the middle
    # vertex of a concatenation, so a new fact is combined only where it helps.
    outgoing: dict[int, dict[int, set[Variable]]] = defaultdict(dict)
    incoming: dict[int, dict[int, set[Variable]]] = defaultdict(dict)
    queue: deque[tuple[int, int, Variable]] = deque()

    def add(source: int, target: int, variable: Variable) -> None:
        variables = reached[source, target]
        if variable in variables:
            return
        variables.add(variable)
        outgoing[source].setdefault(target, set()).add(variable)
        incoming[target].setdefault(source, set()).add(variable)
        queue.append((source, target, variable))

    for source, target, data in graph.edges(data=True):
        for variable in grammar.terminal_productions.get(data["label"], ()):
            add(source, target, variable)

    for node in graph.nodes:
        for variable in grammar.epsilon_productions:
            add(node, node, variable)

    while queue:
        source, target, variable = queue.popleft()

        # variable as the left operand: combine with every (target, k).
        for middle, right_operands in list(outgoing.get(target, {}).items()):
            for right in list(right_operands):
                for head in grammar.binary_productions.get((variable, right), ()):
                    add(source, middle, head)

        # variable as the right operand: combine with every (k, source).
        for middle, left_operands in list(incoming.get(source, {}).items()):
            for left in list(left_operands):
                for head in grammar.binary_productions.get((left, variable), ()):
                    add(middle, target, head)

    start_symbol = grammar.start_symbol
    return {
        (source, target)
        for (source, target), variables in reached.items()
        if start_symbol in variables and source in starts and target in finals
    }
